import {readFileSync,existsSync} from "node:fs";
import assert from "node:assert/strict";
const read=p=>readFileSync(p,"utf8");
const page=read("app/page.tsx"),motion=read("components/FoodIllustrations.tsx"),css=read("app/food-motion.css"),layout=read("app/layout.tsx"),base=read("app/globals.css");
assert(!page.includes("https://images.unsplash.com"),"All image paths must be local");
assert((page.match(/\/media\/\w+\.jpg/g)||[]).length===8,"Eight local image references should be retained");
assert(existsSync("scripts/prepare-media.mjs"));
assert(layout.includes('food-motion.css'),"New food motion CSS must be loaded");
assert(motion.includes('Array.from({length:8}')&&motion.includes("data-food-slice"),"Exactly eight visually detailed pizza slices are required");
assert(motion.includes("const state={angle:0,radius:44,opacity:0}")&&motion.includes("radius:125"),"Each pizza slice must originate from the first and travel outside the disc");
assert(motion.includes("opacity:1,duration:.17")&&motion.includes("i-1)*.55"),"Sequential overlapping timing of pizza slice emergence required");
assert(page.includes("BurgerIllustration")&&page.includes(".food-burger-layer")&&page.includes("pin,"),"Scrollable layered burger scene must be present");
assert(page.includes("FoodIcon kind={c as FoodKind}")&&page.includes('"ساندویچ"'),"Food categories require their matching icons");
assert(!page.includes("✳"),"No unrelated decorative stars");
assert(css.includes(".food-icon")&&css.includes("food-burger-builder"));
assert(base.includes("flex-direction:row-reverse"),"Mobile food menu remains on the right");
